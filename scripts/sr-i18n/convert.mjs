function applyPairs(text, pairs) {
  let out = String(text);
  const sorted = [...pairs].sort((a, b) => b[0].length - a[0].length);
  for (const [from, to] of sorted) {
    if (!from || from === to || !out.includes(from)) continue;
    out = out.split(from).join(to);
  }
  return out;
}

export function toSr(text, { geo = false } = {}) {
  if (typeof text !== 'string') return text;
  let out = applyPairs(text, PAIRS);
  if (geo) out = applyPairs(out, GEO_PAIRS);
  return out;
}

export function mapObject(input, opts = {}) {
  if (Array.isArray(input)) {
    return input.map((item) => {
      if (Array.isArray(item) && item.length >= 2) {
        const next = [...item];
        next[1] = toSr(item[1], opts);
        return next;
      }
      return typeof item === 'string' ? toSr(item, opts) : mapObject(item, opts);
    });
  }
  if (input && typeof input === 'object') {
    const out = {};
    for (const [key, value] of Object.entries(input)) {
      out[key] = typeof value === 'string' ? toSr(value, opts) : mapObject(value, opts);
    }
    return out;
  }
  return input;
}
